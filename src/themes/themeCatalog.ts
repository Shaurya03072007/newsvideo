export function getThemeById(id: string): ThemeDefinition {
  return THEMES_CATALOG.find((t) => t.id === id) || THEMES_CATALOG[0];
}

export function applyThemeToDocument(theme: ThemeDefinition) {
  if (typeof document === 'undefined') return;

  const root = document.documentElement;
  const c = theme.colors;

  // Set CSS Variables
  root.style.setProperty('--pv-bg-page', c.bgPage);
  root.style.setProperty('--pv-bg-surface', c.bgSurface);
  root.style.setProperty('--pv-bg-elevated', c.bgElevated);
  root.style.setProperty('--pv-border', c.border);
  root.style.setProperty('--pv-border-subtle', c.borderSubtle);
  root.style.setProperty('--pv-text-primary', c.textPrimary);
  root.style.setProperty('--pv-text-secondary', c.textSecondary);
  root.style.setProperty('--pv-text-muted', c.textMuted);
  root.style.setProperty('--pv-primary', c.primary);
  root.style.setProperty('--pv-primary-hover', c.primaryHover);
  root.style.setProperty('--pv-primary-text', c.primaryText);
  root.style.setProperty('--pv-accent', c.accent);
  root.style.setProperty('--pv-accent-bg', c.accentBg);
  root.style.setProperty('--pv-tag-bg', c.tagBg);
  root.style.setProperty('--pv-tag-text', c.tagText);
  root.style.setProperty('--pv-card-shadow', c.cardShadow);

  // Set html & body attributes and classes
  root.setAttribute('data-theme-id', theme.id);
  root.setAttribute('data-theme-mode', theme.mode);

  if (theme.mode === 'light') {
    root.classList.remove('dark');
    root.classList.add('light');
    document.body.classList.remove('dark');
    document.body.classList.add('light-theme');
  } else {
    root.classList.remove('light');
    root.classList.add('dark');
    document.body.classList.remove('light-theme');
    document.body.classList.add('dark');
  }

  // Set background of body immediately
  document.body.style.backgroundColor = c.bgPage;
  document.body.style.color = c.textPrimary;
}
